#!/usr/bin/env python3
# save-my-tokens：压缩后提醒。
# Claude Code 每次压缩完上下文，在 SessionStart（matcher: compact）时跑这个脚本，
# 它打印的内容会作为一段提醒放进模型的上下文。只读 stdin，不写任何文件，不联网。
import json
import sys

try:
    d = json.load(sys.stdin)
except Exception:
    d = {}
p = d.get("transcript_path") or "（没拿到路径，找本会话的日志）"
print(f"""上下文刚被压缩过。你手里的是摘要，不是完整记录：命令原文、报错原文、文件路径、数字、用户原话，摘要里可能没有或不准。
继续之前，要用到这类细节的，先回压缩前的完整记录里核对：{p}
摘要会悄悄丢事，丢了的你不会有感觉；它偏向最近在做的事，较早提过、没做完的事最容易被丢。
问到进度、还剩什么、下一步，或者你要接着干活之前，先补一遍，不用写文件、不用列清单。
1. 记录里如果有更早的摘要，较早摘要里有、这次摘要里没有的事，逐条列出来。
2. 从记录开头起过一遍用户说过的话，把提过的要求、问过的问题、说好之后再做的事逐条列出来。
3. 逐条确认做完没有：看记录里的结果，或者现在的文件、提交、测试输出，不凭摘要的说法。摘要和记录对不上时，以记录为准。
记录是 JSONL，很大：先看大小，只取要核对的那几段，看对话、命令和结果就够了。""")
