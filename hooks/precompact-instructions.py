#!/usr/bin/env python3
# save-my-tokens：压缩前要求。
# Claude Code 每次压缩上下文之前（PreCompact，手动和自动都算）跑这个脚本，
# 它打印的内容会附在 Claude Code 自带的摘要要求后面，交给写摘要的模型。
# 只打印纯文本，不读输入，不写任何文件，不联网。
# 用中文写：同一批压缩上实测过中文和英文两种写法，中文这版保住的事更多（见 references/compact-hook.md）。
print("""对话里如果已经有一份更早的摘要：它列的待办和用户纠正过的要求，只要后面的对话没有解决或推翻，就带进这份摘要。
「待办」一节除了用户明确交代的任务，还要列：问了用户还没得到回答的问题（保留原话）、自己说过还没验证或没复查的地方、只在本地还没提交或没推送的改动。
已经做完的、被用户否掉的、被后来的话取代的旧事不带。从更早的摘要带过来的每条写成一个指针：一句话说清是什么事，再留下能在完整记录里搜到它的原词，比如用户原话里的关键短语、文件路径、编号；细节留在记录里，不抄。""")
